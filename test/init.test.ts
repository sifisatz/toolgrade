import { join } from "node:path";
import { parse } from "yaml";
import { describe, expect, it } from "vitest";
import { loadSuite, parseSuite } from "../src/config.js";
import { generateSuite, todoTasks } from "../src/init.js";
import type { McpTool } from "../src/mcp.js";
import { openSession } from "../src/mcp.js";
import { ScriptedProvider } from "../src/providers/scripted.js";
import { runSuite } from "../src/runner.js";

const NOTES = join(import.meta.dirname, "..", "examples", "notes-suite.yaml");

const tool = (t: Partial<McpTool> & { name: string }): McpTool => ({ inputSchema: {}, ...t });

describe("toolgrade init", () => {
  it("generates a valid suite with one task per tool and a control task, from a real server", async () => {
    const real = await loadSuite(NOTES);
    const session = await openSession(real.server);
    const result = generateSuite("notes", { command: "node", args: ["--import", "tsx", "server.ts"], cwd: "notes-server" }, session.tools);
    await session.close();

    const suite = parseSuite(parse(result.yaml), join(import.meta.dirname, "..", "examples"));
    expect(suite.tasks.map((t) => t.id)).toEqual(["search-notes", "get-note", "create-note", "delete-note", "list-tags", "control-no-tools-needed"]);
    expect(result.yaml).toContain("# Generated by `toolgrade init`");

    // The notes tools have real descriptions and schemas, so generation should produce real
    // drafts, not bare TODOs - this is exactly the gap this feature closes.
    expect(result.generated).toBe(5);
    expect(result.fallback).toBe(0);
    expect(todoTasks(suite.tasks)).toHaveLength(0);

    // delete_note is destructive: falls back to a placeholder output_contains, never a fabricated llm rubric.
    const deleteTask = suite.tasks.find((t) => t.id === "delete-note")!;
    expect(deleteTask.assert.some((a) => a.type === "llm")).toBe(false);
    expect(deleteTask.assert.some((a) => a.type === "tool_called" && a.name === "delete_note")).toBe(true);
    expect(deleteTask.assert.some((a) => a.type === "output_contains")).toBe(true);
  });

  it("gives colliding tool names unique task ids", () => {
    const tools = [tool({ name: "a_b" }), tool({ name: "a-b" })];
    const result = generateSuite("x", { url: "http://localhost:1/mcp" }, tools);
    const suite = parseSuite(parse(result.yaml), "/");
    expect(suite.tasks.map((t) => t.id)).toEqual(["a-b", "a-b-2", "control-no-tools-needed"]);
  });

  it("a tool with a required string param generates a concrete prompt and a tool_called assertion", () => {
    const tools = [
      tool({
        name: "get_note",
        description: "Read one note in full by its id. Returns title, owner, tags and body.",
        inputSchema: { type: "object", properties: { id: { type: "string", description: "Note id" } }, required: ["id"] },
      }),
    ];
    const result = generateSuite("x", { url: "http://localhost:1/mcp" }, tools);
    const suite = parseSuite(parse(result.yaml), "/");
    const task = suite.tasks.find((t) => t.id === "get-note")!;

    expect(task.prompt.startsWith("TODO")).toBe(false);
    expect(task.prompt).toMatch(/id/i);
    expect(task.prompt).toMatch(/demo-1|example-value/);
    expect(task.assert).toContainEqual(expect.objectContaining({ type: "tool_called", name: "get_note" }));
    expect(result.generated).toBe(1);
    expect(result.fallback).toBe(0);
  });

  it("a tool with no required params generates a simpler prompt directly from its description", () => {
    const tools = [tool({ name: "list_tags", description: "List every tag in use with its note count. Useful to discover what topics exist." })];
    const result = generateSuite("x", { url: "http://localhost:1/mcp" }, tools);
    const suite = parseSuite(parse(result.yaml), "/");
    const task = suite.tasks.find((t) => t.id === "list-tags")!;

    expect(task.prompt.startsWith("TODO")).toBe(false);
    expect(task.prompt).not.toMatch(/Use .* for/);
    expect(task.prompt).toMatch(/list/i);
    expect(task.assert).toContainEqual(expect.objectContaining({ type: "tool_called", name: "list_tags" }));
  });

  it("a destructive tool with no state-check capability falls back to output_contains, not a fabricated llm rubric", () => {
    const tools = [
      tool({
        name: "delete_note",
        description: "Permanently delete a note by id. Find the id with search_notes first.",
        inputSchema: { type: "object", properties: { id: { type: "string" } }, required: ["id"] },
      }),
    ];
    const result = generateSuite("x", { url: "http://localhost:1/mcp" }, tools);
    const suite = parseSuite(parse(result.yaml), "/");
    const task = suite.tasks.find((t) => t.id === "delete-note")!;

    expect(task.assert.some((a) => a.type === "llm")).toBe(false);
    expect(task.assert.some((a) => a.type === "output_contains")).toBe(true);
    expect(task.assert.some((a) => a.type === "tool_called" && a.name === "delete_note")).toBe(true);
    expect(result.fallback).toBe(0);
  });

  it("falls back near-duplicate generated prompts to the TODO placeholder when they can't be varied apart", () => {
    // Two tools with near-identical names/descriptions will generate near-identical prompts.
    // Either suite-lint's duplicate check gets satisfied by the mechanical variation, or the
    // second task falls back to a TODO placeholder - either way the final suite must not trip
    // suite-lint's near-duplicate warning silently.
    const tools = [
      tool({ name: "archive_item", description: "Archive an item by id.", inputSchema: { type: "object", properties: { id: { type: "string" } }, required: ["id"] } }),
      tool({ name: "archive_entry", description: "Archive an item by id.", inputSchema: { type: "object", properties: { id: { type: "string" } }, required: ["id"] } }),
    ];
    const result = generateSuite("x", { url: "http://localhost:1/mcp" }, tools);
    const suite = parseSuite(parse(result.yaml), "/");

    const a = suite.tasks.find((t) => t.id === "archive-item")!;
    const b = suite.tasks.find((t) => t.id === "archive-entry")!;
    // Either the mechanical variation broke the duplicate match, or the task fell back to TODO -
    // either way the two prompts must no longer be byte-identical, and suite-lint must be clean.
    expect(a.prompt === b.prompt).toBe(false);
    expect(result.fallback + result.generated).toBe(2);
  });

  it("refuses to run a suite that still has TODO placeholders, before any model call", async () => {
    const real = await loadSuite(NOTES);
    const raw = {
      name: "x",
      server: { url: "http://localhost:1/mcp" },
      tasks: [
        {
          id: "t",
          prompt: "TODO: write a request a real user would make that needs t.",
          assert: [
            { type: "tool_called", name: "t" },
            { type: "llm", rubric: "TODO: describe what a correct outcome looks like." },
          ],
        },
        {
          id: "control-no-tools-needed",
          tags: ["control"],
          prompt: "What is 17 * 23? Reply with just the number.",
          assert: [
            { type: "output_contains", value: "391" },
            { type: "max_tool_calls", value: 0 },
          ],
        },
      ],
    };
    const suite = parseSuite(raw, "/");
    suite.server = real.server;
    const provider = new ScriptedProvider(() => ({ text: "x" }));
    await expect(runSuite(suite, { provider })).rejects.toThrow(/TODO placeholders in: t/);
    expect(provider.requests).toHaveLength(0);
    // The finished control task alone is runnable.
    await expect(runSuite(suite, { provider, filter: "control", trials: 1 })).resolves.toBeDefined();
  });
});
