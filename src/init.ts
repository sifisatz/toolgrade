import { stringify } from "yaml";
import { SuiteSchema, type AssertionSpec, type Suite } from "./config.js";
import { ACTION_VERBS, DESTRUCTIVE_VERBS } from "./lint.js";
import type { McpTool } from "./mcp.js";
import { lintSuiteValidity } from "./suite-lint.js";

export type InitServer = { command: string; args: string[]; cwd: string } | { url: string };

export const TODO_PREFIX = "TODO:";

export interface GenerateSuiteResult {
  yaml: string;
  /** Count of tasks that got a real heuristic prompt + deterministic assertion(s). */
  generated: number;
  /** Count of tasks that fell back to the TODO placeholder (generation had nothing to work with, or tripped suite-lint). */
  fallback: number;
  /** One short reason per fallback task, e.g. `tool-x: near-duplicate prompt`. */
  fallbackReasons: string[];
}

const CONTROL_TASK = {
  id: "control-no-tools-needed",
  tags: ["control"],
  prompt: "What is 17 * 23? Reply with just the number.",
  assert: [
    { type: "output_contains", value: "391" },
    { type: "max_tool_calls", value: 0 },
  ],
};

/** Past-tense success word for each destructive verb, for a placeholder output_contains check. */
const SUCCESS_PHRASES: Record<string, string> = {
  delete: "deleted",
  remove: "removed",
  drop: "dropped",
  truncate: "truncated",
  wipe: "wiped",
  revoke: "revoked",
  terminate: "terminated",
  kill: "killed",
  destroy: "destroyed",
};

interface Draft {
  id: string;
  tool: McpTool;
  prompt: string;
  assert: AssertionSpec[];
  /** Author-facing note on a generated-but-placeholder assertion (stripped on load, kept in the written YAML). */
  note?: string;
  fellBack: boolean;
  fallbackReason?: string;
}

/**
 * A starter suite: one task per tool plus a no-tool control task. Each tool task gets a
 * mechanically-derived prompt and deterministic assertions from its schema and description -
 * a draft the author edits, not a blank TODO. Generation falls back to the old TODO placeholder
 * (which `run` refuses) only when nothing sensible could be derived, or when the draft trips
 * suite-lint's quality checks and can't be mechanically fixed.
 */
export function generateSuite(name: string, server: InitServer, tools: McpTool[]): GenerateSuiteResult {
  const used = new Set<string>(["control-no-tools-needed"]);
  const uniqueId = (base: string) => {
    let id = base;
    for (let i = 2; used.has(id); i++) id = `${base}-${i}`;
    used.add(id);
    return id;
  };

  const drafts: Draft[] = tools.map((tool) => {
    const id = uniqueId(slug(tool.name));
    const { prompt, assert, note } = generateTask(tool);
    return { id, tool, prompt, assert, note, fellBack: false };
  });

  reconcileWithSuiteLint(name, server, drafts);

  const tasks = [...drafts.map((d) => taskObj(d)), CONTROL_TASK];
  const doc = {
    name,
    server,
    agent: { model: "claude-opus-5", max_turns: 10 },
    judge: { model: "claude-sonnet-5" },
    run: { trials: 3, baseline: true, concurrency: 4 },
    gate: { min_pass_rate: 0.8, min_lift: 0.2 },
    tasks,
  };
  const header = [
    "# Generated by `toolgrade init`. Before running:",
    "#  1. Replace any remaining TODO prompts with a real user request (run refuses TODO prompts).",
    "#  2. Review the generated prompts and assertions - tighten placeholder output_contains checks,",
    "#     ideally with state assertions once you know the server's actual resources.",
    "#  3. Delete tasks for tools you do not want graded, and add tasks that need several tools.",
    "",
  ].join("\n");

  const generated = drafts.filter((d) => !d.fellBack).length;
  const fallback = drafts.filter((d) => d.fellBack).length;
  const fallbackReasons = drafts.filter((d) => d.fellBack).map((d) => `${d.tool.name}: ${d.fallbackReason}`);

  return { yaml: header + stringify(doc, { lineWidth: 0 }), generated, fallback, fallbackReasons };
}

/** Human-readable one-line summary, e.g. for the CLI to print after `init`. */
export function formatGenerationSummary(result: GenerateSuiteResult): string {
  const total = result.generated + result.fallback;
  if (result.fallback === 0) return `Generated ${result.generated} real draft task(s) out of ${total}.`;
  return `Generated ${result.generated} real draft task(s), ${result.fallback} fell back to TODO placeholders (${result.fallbackReasons.join("; ")}).`;
}

export function todoTasks(tasks: Array<{ id: string; prompt: string; assert: Array<{ type: string; rubric?: string }> }>): string[] {
  return tasks
    .filter((t) => t.prompt.trimStart().startsWith(TODO_PREFIX) || t.assert.some((a) => a.type === "llm" && a.rubric?.trimStart().startsWith(TODO_PREFIX)))
    .map((t) => t.id);
}

function taskObj(d: Draft): Record<string, unknown> {
  const base: Record<string, unknown> = { id: d.id, tags: ["generated"], prompt: d.prompt, assert: d.assert };
  if (d.note) base.note = d.note;
  return base;
}

/**
 * Run the draft suite through cycle 2's static suite auditor. Any `warn` finding (near-duplicate
 * prompt, unfalsifiable judge-only task) gets one mechanical fix attempt; if that doesn't clear
 * it, that single task falls back to the TODO placeholder rather than shipping a draft the
 * auditor itself flags as low quality.
 */
function reconcileWithSuiteLint(name: string, server: InitServer, drafts: Draft[]): void {
  const byId = new Map(drafts.map((d) => [d.id, d]));
  const lint = () => lintSuiteValidity(SuiteSchema.parse(checkDoc(name, server, drafts)) as Suite);

  let findings = lint().filter((f) => f.severity === "warn");
  if (findings.length === 0) return;

  for (const f of findings) {
    const draft = byId.get(f.taskId);
    if (!draft || draft.fellBack) continue;
    if (/is ~\d+% similar to/.test(f.message)) {
      draft.prompt = varyPrompt(draft.prompt, draft.tool.name);
    } else {
      fallBack(draft, f.message);
    }
  }

  // Re-check: anything still flagged after the mechanical fix falls back outright.
  findings = lint().filter((f) => f.severity === "warn");
  for (const f of findings) {
    const draft = byId.get(f.taskId);
    if (draft && !draft.fellBack) fallBack(draft, f.message);
  }
}

function fallBack(draft: Draft, reason: string): void {
  const fallback = generateTodoTask(draft.tool);
  draft.prompt = fallback.prompt;
  draft.assert = fallback.assert;
  draft.note = undefined;
  draft.fellBack = true;
  draft.fallbackReason = reason.length > 120 ? `${reason.slice(0, 117)}...` : reason;
}

function varyPrompt(prompt: string, toolName: string): string {
  return `${prompt.replace(/\s+$/, "")} (This task specifically exercises the ${toolName} tool.)`;
}

function checkDoc(name: string, server: InitServer, drafts: Draft[]): Record<string, unknown> {
  return { name, server, tasks: [...drafts.map((d) => taskObj(d)), CONTROL_TASK] };
}

function generateTodoTask(tool: McpTool): { prompt: string; assert: AssertionSpec[] } {
  return {
    prompt: `${TODO_PREFIX} write a request a real user would make that needs ${tool.name}. Tool says: ${oneLine(tool.description) || "(no description)"}`,
    assert: [
      { type: "tool_called", name: tool.name, min_times: 1 },
      { type: "llm", rubric: `TODO: describe what a correct outcome looks like. Prefer a state or output_contains assertion where you can.` },
    ],
  };
}

/** Heuristic draft: a plausible prompt plus deterministic assertions, derived from the tool's schema. */
function generateTask(tool: McpTool): { prompt: string; assert: AssertionSpec[]; note?: string } {
  const prompt = generatePrompt(tool);
  const assert: AssertionSpec[] = [{ type: "tool_called", name: tool.name, min_times: 1 }];
  let note: string | undefined;

  const destructiveVerb = isDestructive(tool);
  if (destructiveVerb) {
    // No way to know this server's resources from the schema alone, so no `state` check is
    // possible here - fall back to a deterministic (if generic) output_contains, clearly flagged.
    const successWord = SUCCESS_PHRASES[destructiveVerb] ?? destructiveVerb;
    assert.push({ type: "output_contains", value: successWord, mode: "any", case_sensitive: false, negate: false });
    note = `PLACEHOLDER: output_contains("${successWord}") assumes a plausible success phrase for this destructive tool. Tighten it, or replace it with a "state" assertion, once you know ${tool.name}'s real response and the server's resources.`;
  }

  return { prompt, assert, note };
}

function generatePrompt(tool: McpTool): string {
  const phrase = actionPhrase(tool);
  const required = requiredParams(tool);
  if (required.length === 0) return phrase;

  const first = required[0]!;
  const value = exampleValue(first.name, first.schema);
  if (value === undefined) return phrase;

  const valueStr = typeof value === "string" ? `'${value}'` : String(value);
  return `${phrase} Use ${valueStr} for ${first.name}.`;
}

/** The tool's description turned into an imperative action phrase, anchored on its first action verb. */
function actionPhrase(tool: McpTool): string {
  const desc = firstSentence(tool.description ?? "");
  if (!desc) return `${capitalize(toWords(tool.name).join(" "))}.`;

  const tokens = desc.split(/\s+/);
  const idx = tokens.findIndex((tok) => ACTION_VERBS.has(normalizeWord(tok)));
  const phrase = idx >= 0 ? tokens.slice(idx).join(" ") : desc;
  return /[.!?]$/.test(phrase) ? capitalize(phrase) : `${capitalize(phrase)}.`;
}

function isDestructive(tool: McpTool): string | undefined {
  const haystack = `${tool.name} ${tool.description ?? ""}`.toLowerCase();
  return DESTRUCTIVE_VERBS.find((v) => haystack.includes(v));
}

function requiredParams(tool: McpTool): Array<{ name: string; schema: Record<string, unknown> }> {
  const props = (tool.inputSchema?.properties as Record<string, Record<string, unknown>> | undefined) ?? {};
  const required = (tool.inputSchema?.required as string[] | undefined) ?? [];
  return required.filter((r) => r in props).map((r) => ({ name: r, schema: props[r]! }));
}

function exampleValue(paramName: string, schema: Record<string, unknown>): string | number | boolean | undefined {
  const enumVals = schema.enum as unknown[] | undefined;
  if (Array.isArray(enumVals) && enumVals.length > 0 && typeof enumVals[0] === "string") return enumVals[0] as string;

  const type = schema.type as string | undefined;
  if (type === "number" || type === "integer") return 42;
  if (type === "boolean") return true;
  if (type === "string" || type === undefined) {
    return /(^|[-_])id$/i.test(paramName) ? "demo-1" : "example-value";
  }
  return undefined;
}

function toWords(name: string): string[] {
  return name
    .replace(/[_-]+/g, " ")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .toLowerCase()
    .split(/\s+/)
    .filter(Boolean);
}

function normalizeWord(tok: string): string {
  return tok.toLowerCase().replace(/[^a-z]/g, "");
}

function capitalize(s: string): string {
  return s ? s[0]!.toUpperCase() + s.slice(1) : s;
}

function firstSentence(desc: string): string {
  const s = oneLine(desc);
  const m = s.match(/^.*?[.!?](?=\s|$)/);
  return (m ? m[0] : s).trim();
}

function slug(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "tool";
}

function oneLine(s: string | undefined): string {
  return (s ?? "").replace(/\s+/g, " ").trim().slice(0, 200);
}
